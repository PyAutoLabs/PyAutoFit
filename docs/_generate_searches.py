"""
Generate the search documentation pages from the search manifest.

    python docs/_generate_searches.py          # (re)write the generated pages
    python docs/_generate_searches.py --check  # exit 1 if any page is out of date

The pages are generated from ``python -m autofit search-manifest --json``
(``search-manifest@1``, built by ``autofit/non_linear/search/registry.py``) and
``files/citations.bib``; they are never edited by hand:

- ``docs/api/searches.rst``: the API reference, one autosummary block per family;
- ``docs/searches/index.rst``: the capability matrix ("which search");
- ``docs/searches/citations.rst``: the canonical citations page for the searches.

The pages deliberately omit ``autofit_version``, so a version bump never makes them
stale; only a change to the registry or the bibliography does.

Run from anywhere: paths resolve relative to this file. ``--check`` is run by the Docs
workflow (``.github/workflows/docs.yml``) and by ``test_autofit``.
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Dict, List

DOCS = Path(__file__).resolve().parent
REPO = DOCS.parent
BIB = REPO / "files" / "citations.bib"

HEADER = (
    ".. This file is generated by docs/_generate_searches.py from the search manifest\n"
    "   (python -m autofit search-manifest --json). Do not edit it by hand: change\n"
    "   autofit/non_linear/search/registry.py (or files/citations.bib) and re-run the\n"
    "   generator.\n\n"
)

# Bibliography fields left out of the rendered entries: long, or local to an author's
# machine. The full entries stay in files/citations.bib.
_DROPPED_BIB_FIELDS = ("abstract", "file", "keywords", "mendeley-groups")


def load_manifest() -> dict:
    """
    The search manifest, read through the public CLI exactly as other repos read it.
    """
    output = subprocess.run(
        [sys.executable, "-m", "autofit", "search-manifest", "--json"],
        capture_output=True,
        text=True,
        check=True,
        cwd=REPO,
    ).stdout
    return json.loads(output)


def _searches_by_family(manifest: dict) -> Dict[str, List[dict]]:
    grouped = {family: [] for family in manifest["families"]}
    for search in manifest["searches"]:
        grouped[search["family"]].append(search)
    return grouped


def _yes(value: bool) -> str:
    return "yes" if value else "no"


def _link(search: dict) -> str:
    return f":class:`~autofit.{search['name']}`"


